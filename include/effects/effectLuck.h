#ifndef EFFECT_LUCK_H
#define EFFECT_LUCK_H

#include "effects/effects.h"

/**
 * @class EffectLuck
 * @brief Класс, представляющий эффект удачи для персонажа.
 * 
 * Этот класс описывает эффект, который увеличивает вероятность попадания
 * для персонажа на определённое количество ходов.
 */
class EffectLuck : public Effect
{
private:
    int luck; ///< Сила эффекта удачи (на сколько увеличивается вероятность попадания).
    bool isActive; ///< Флаг, указывающий, активен ли эффект удачи.

public:
    /**
     * @brief Конструктор класса EffectLuck.
     * 
     * Инициализирует объект эффекта удачи для заданного персонажа.
     * Устанавливает продолжительность эффекта, его силу и время восстановления.
     * 
     * @param ch Указатель на персонажа, к которому применяется эффект.
     */
    EffectLuck(Character* ch) : Effect::Effect(ch)
    {
        turnDur = 4; ///< Эффект длится 4 хода.
        luck = 2; ///< Эффект увеличивает вероятность попадания на 2.
        isActive = false; ///< Эффект не активен по умолчанию.
        coolDown = 3; ///< Время восстановления эффекта составляет 3 хода.
    }

    /// Деструктор класса EffectLuck.
    ~EffectLuck() = default;

    /**
     * @brief Применяет эффект удачи к персонажу.
     * 
     * Увеличивает вероятность попадания персонажа на текущий ход, если эффект активен.
     */
    void affect() override;

    /**
     * @brief Проверяет, возможно ли применить эффект удачи.
     * 
     * @return true, если эффект может быть применён (например, если персонаж может двигаться и эффект ещё не активен).
     */
    bool isPossible() override;

    /**
     * @brief Возвращает описание эффекта удачи.
     * 
     * @return Строка, описывающая эффект (например, "Увеличивает вероятность попадания на 2 на 4 хода").
     */
    std::string effectDescription() override;
};

#endif
